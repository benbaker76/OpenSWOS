/*
 * world_cupd.h -- the Coppa Italia Serie D (src/world_cupd.c; docs/WORLD_2026_27.md,
 * phase 4), as the SWOS 96/97 Mod plays it (tools/gplay.c cd_*, tools/cupd.py).
 *
 * 162 clubs from a preliminary round -- past what the game's cups hold (64) -- so the cup
 * is the Mod's own: a table of rounds and ties (the real 2026-27 draw and its results to
 * the fetch day; a later round's tie can be a previous round's tie, its winner), stepped at
 * every calendar advance (Career_AdvanceToNextTeamSelectionKeyCacheEntry): each round whose
 * week has come is decided tie by tie -- in the world's first season by its real result when
 * known, else by strength (the best 11 players' prices: the Mod's statesim).
 *
 * The career club's tie is played: a contest of one tie in slot 4 (as the Mod's cd_ko),
 * dated at its round's weeks -- built as soon as both its clubs are known (the Mod builds it
 * when the calendar reaches the round: with our calendar's entries a round could fall after
 * the next league match) -- its result back to the cup. Single matches go to penalties with
 * no extra time; the semi-finals and the final are two legs. A decided tie's record stays in
 * slot 4 (the calendar still lists its matches) until the next tie, or a world's play-off at
 * the league's end, takes the slot; 96/97's slot-4 rebuild is not for it.
 *
 * From the second season the Mod's entry rule (cd_rank, cd_season, cd_make): the season's
 * Serie D clubs in an entry order -- the new arrivals (relegated from Serie C, a slot that
 * took a pool club), then each group's clubs from the bottom of last season's table up --
 * the first 2 x (N - 128) playing a preliminary round, the others entering at the first;
 * both rounds paired within a group where possible, else at random; from the third round a
 * fixed bracket (tie k: the winners of ties 2k, 2k + 1), the table's weeks, hosts and
 * drawn semi-finals.
 */
#ifndef WORLD_CUPD_H
#define WORLD_CUPD_H

#include "swos_types.h"

/* The cup's data (world_data.c, generated by world_import.py italian_cupd). A side is a
 * team word as the Mod's (file | ordinal << 8; here the file is the country), a previous
 * round's tie (index << 8 | FFh), drawn (FEFFh) or 0 (a club outside the file). */
typedef struct {
    uint8_t          country;
    uint8_t          rounds;
    const uint8_t  (*round)[8];     /* week 1, week 2 (two legs), legs, host (0 listed, 2 drawn,
                                       4 alternate), ties, flags (1 drawn pairs, 2 pens), first tie */
    uint8_t          ties;
    const uint8_t  (*tie)[6];       /* a (lo, hi), b (lo, hi), the real winner (0, 1, 2), - */
    uint8_t          first, groups; /* the Serie D level: its first division, its groups */
    const uint8_t   *base;          /* each ordinal's base division (FFh: none) */
    const uint16_t  *strength;      /* each ordinal's (its own record's) */
    uint8_t          pool;
    const uint16_t  *poolStrength;  /* the pool's clubs' (team_pool.h's identities 256 + k) */
    char            *name[2];
} WorldCupD;

const WorldCupD *World_CupD(void);  /* (world_data.c; 0: the world has none) */

#define WORLD_CUPD_TIES 168         /* (gplay.c CDT) */
#define WORLD_CUPD_PRE 41           /* a generated preliminary round's ties at most (CDP) */
#define WORLD_CUPD_R1 64            /* a generated first round's ties (CD1) */

/* The cup's state this season (saved with the career; gplay.c struct cd_state). */
typedef struct {
    uint8_t season;                 /* (world_cups.h's seasons + 1; 0: not started) */
    uint8_t round;                  /* the round to come */
    uint8_t drawn;                  /* the round (+ 1) whose pairs are drawn (sd) */
    uint8_t res[WORLD_CUPD_TIES];   /* each tie's winner: 1 a, 2 b, 0 not decided */
    uint8_t home[WORLD_CUPD_TIES];  /* 0 a hosted (the first leg), 1 b */
    uint8_t sd[4];                  /* a drawn round's ties: the previous round's, drawn */
    uint8_t built;                  /* the career club's tie is in slot 4: */
    uint8_t bt;                     /* which, */
    uint8_t d1, d2, legs;           /* its weeks, its legs, */
    uint16_t teamA, teamB;          /* its clubs, home first ({country, ordinal}) */
    uint8_t gen;                    /* this season's rounds 0-1 generated (not the table's): */
    uint8_t np;                     /* its preliminary ties, */
    uint16_t side[2 * (WORLD_CUPD_PRE + WORLD_CUPD_R1)];   /* tie t's sides 2t, 2t + 1 */
} WorldCupDState;

extern WorldCupDState g_worldCupD;

/* A new career. */
void CupD_Reset(void);

/* The calendar has played the entry of `week` (its key): the rounds that have come. */
void CupD_Step(uint16_t week);

/* The season's calendar is made (InitializeNewSeason): the rounds before its first entry. */
void CupD_SeasonStart(void);

/* A tie was decided (ProcessDIYKnockoutMatchResultAndCareerUpdates): the career club's
 * Coppa Italia Serie D tie, its result. */
void CupD_TieDecided(uint16_t team1, uint16_t team2, int32_t team2Won);

/* Slot 4 holds the career club's tie (built: 2; decided, not yet let go: 1). */
int32_t CupD_InSlot4(void);

/* After a career is loaded: slot 4 back on the tie, if one is under way. */
void CupD_RestoreSlot(void);

/* A round's name in the cup round tables for the tie under way, -1 if not ours. */
int32_t CupD_RoundStringIndex(uint8_t compId);

/* The season end has the final tables (league_playoffs.c, before the moves): each club's
 * division, a Serie D club's place from the bottom (gplay.c cd_rank). */
void CupD_KeepPlace(uint8_t country, uint16_t division, uint16_t team, int32_t place, int32_t clubs);

/* The season end gave a slot a pool club's identity: a new arrival next season. */
void CupD_NoteArrival(uint8_t country, uint8_t ordinal);

/* The career club is a Coppa Italia Serie D club this season (a Serie D club: it plays no
 * Coppa Italia and no Serie C cup, gplay.c cd_member_c). */
int32_t CupD_Member(uint8_t country, uint8_t ordinal);

#endif
