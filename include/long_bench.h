/*
 * long_bench.h -- benches of up to 15 substitutes in a world's matches (src/long_bench.c;
 * docs/WORLD_2026_27.md, "Long benches"): the SWOS 96/97 Mod's tools/benchx.py (4.0.5 / 4.1),
 * Davide Lorigliola's, MIT.
 *
 * The game builds each in-match team with 16 players -- 11 and a bench of up to 5 (the
 * competition's maxSubs). A World 2026-27 match names the substitutes its competition's real
 * rule names (tools/bench2627.json: Serie A 15, LaLiga 12, the Premier League 9 ...): a career's
 * by its competition (a league by the club's division, a cup by its name, a continental cup by
 * its name, any other contest of the country its top league's), a friendly or DIY match the
 * longer of its two clubs' (country, division) benches, 5 substitutions everywhere. 96/97, the
 * classic worlds, national and custom teams, training: the game's own bench and changes.
 *
 * The places past the game's 16 (17..26) live beside the two in-match teams (g_lbExtra; the game's
 * `ingameTeamPlayerOffsets` run to 26 and bench_subs.c reaches a place through LongBench_Player);
 * they are match state only while a match has a long bench (src/sim_state.c), so a 96/97 match's
 * state is the bytes it always was.
 *   - the managed club: its squad order's places 16.. (careerTeam's, up to 30);
 *   - any other club: its 16, then its players 17.. still at the club (squad_extras.c);
 *   - a place with nobody (or an injured / suspended substitute): empty, as a substituted player.
 * In the match the dugout shows five at a time and scrolls with the cursor (the Mod's 4.0.5); a
 * substitute from place 17 on gets a name sprite of his own (sprites from LB_NAME_SPRITE_BASE, SDL).
 *
 * SDL only in practice: the Amiga has no world's squads beyond 16 and reads no JSON, so every
 * match there has the game's bench (LongBench_Places() == 16).
 */
#ifndef LONG_BENCH_H
#define LONG_BENCH_H

#include "swos_types.h"
#include "game_types.h"
#include "player_looks.h"   /* LOOKS_SPRITES_END: the long bench's name sprites follow the looks' sets */

#define LB_MAX_SUBS       15                    /* the most named substitutes (the Mod's cap) */
#define LB_PLACES_MAX     (11 + LB_MAX_SUBS)    /* 26 */
#define LB_GAME_PLACES    16                    /* the game's in-match team */
#define LB_EXTRA_PLACES   (LB_PLACES_MAX - LB_GAME_PLACES)   /* 10: places 17..26 */
#define LB_USED           5                     /* substitutions allowed with a long bench */

/* World data (src/world_benches.c, generated by scripts/world_benches.py). */
typedef struct {
    uint8_t country;            /* the country's team file number */
    uint8_t division;           /* its league's division, 0xFF: the country's own (top league /
                                 * its confederation's) */
    uint8_t named, et;          /* named substitutes; 1: one more substitution in extra time */
} LongBenchDiv;
typedef struct {
    uint8_t     country;        /* 0: a continental contest (any country) */
    uint8_t     named, et;
    const char *name;           /* the contest's name, as a pack names it (upper case) */
} LongBenchTitle;
#if SWOS_WORLDS
extern const LongBenchDiv   g_worldBenchDivs[];
extern const int32_t        g_worldBenchDivCount;
extern const LongBenchTitle g_worldBenchTitles[];
extern const int32_t        g_worldBenchTitleCount;
#endif

/* ---- the match ---- */

/* At the kick-off (InitializeInGameTeamsAndStartGame), before the in-match teams are built: this
 * match's bench. `maxSubs` / `minSubs` are the game's (bench, substitutions allowed); with a long
 * bench they become the competition's. Sets LongBench_Places(). */
void     LongBench_MatchStart(const TeamFile *team1, const TeamFile *team2, int16_t *minSubs, int16_t *maxSubs);
/* The same decided early (a netplay session sizes its states before the kick-off: NetplayMatch_Start,
 * _StartResim), and undone after the match (InitializeInGameTeamsAndStartGame's end): between
 * matches -- a lobby's state sent at START among them -- the state is the game's. */
void     LongBench_Prepare(const TeamFile *team1, const TeamFile *team2);
void     LongBench_MatchEnd(void);
/* A friendly club's own order of its places (16 + its players 17..: world friendlies and DIY
 * matches with a long bench, offline): active for the two teams of the pre-match screen / the
 * kick-off; GetPlayerAtIndex reads it, the pre-match screen swaps and rotates it. NULL: none. */
void           LongBench_FrActivate(const TeamFile *team1, const TeamFile *team2, int32_t on);
const uint8_t *LongBench_FrOrder(uint16_t team, uint16_t *count);
int32_t        LongBench_FrSwap(uint16_t team, int16_t a, int16_t b);
int32_t        LongBench_FrRotate(uint16_t team, uint16_t from);
/* The pre-match screens' bench for these two teams (ShowPlayMatchMenu): over 5, or 0. */
uint16_t LongBench_PreMatch(const TeamFile *team1, const TeamFile *team2);
/* The places of each in-match team: 16 (the game's), or 11 + the bench (17..26). */
uint16_t LongBench_Places(void);
int32_t  LongBench_On(void);                    /* this match has a bench over 5 */
/* The two-row dugouts (a long bench, not a training game): both benches seated in two rows, the
 * dugouts a row longer and a column wider (LongBench_PitchDugouts, from FixupAndColorPitchFile), the
 * bench camera at the halfway line, the clock aside while the bench is open. */
int32_t  LongBench_TwoRows(void);
#define LB_BACK_ROW   7                 /* places in the back row, after the coach */
#define LB_FRONT_X    9                 /* the front row: towards the pitch (y: 53 up, place 8 level with the coach) */
#define LB_ARROW_DX   41                /* the front row's arrow, mirrored, right of it */
#define LB_TOP_BENCH_Y 373              /* the top dugout grew a row upwards (389 - 16) */
#define LB_CAM_Y      450               /* the bench camera's y: both dugouts whole in view */
void     LongBench_PitchDugouts(uint8_t **tiles);
/* The bench cursor's last place (1-based): 5, or the bench (5 in a training game). */
uint16_t LongBench_Last(void);
/* Places 16..25 of the top (0) and bottom (1) in-match teams. */
extern PlayerInfo g_lbExtra[2][LB_EXTRA_PLACES];
/* The substitutions a team may make now: _maxSubsPerTeam, one more in extra time where the
 * competition has it (bench2627.json's "et": the FA Cup, the UEFA cups ...). */
uint16_t LongBench_SubsAllowed(void);
/* An in-match team's player at `place` (0..25). */
PlayerInfo *LongBench_Player(TeamGame *tg, uint16_t place);
/* InitInGameTeamStructure for a place from 16 on. */
void     LongBench_InitPlace(TeamFileEx *team, TeamGame *tg, uint16_t place);
/* An in-match player's record (GetPlayer's view: the PlayerFile at +76) by his file index, for the
 * after-match write-backs and the bench's strip: GetPlayer for the game's 16 and the managed club,
 * another club's player 17.. from its block (squad_extras.c); NULL: none. */
uint8_t *LongBench_Record(const TeamFileEx *team, int8_t playerIndex);
/* PlayDIYLeagueMatchAndCacheResult: the next kick-off is a league's (a career's bench by division). */
void     LongBench_LeagueMatch(int32_t on);
/* The kick-off state of the places 17.. (InitGameSaveTeams / InitGameRestoreTeams: the match
 * played again from its kick-off). */
void     LongBench_SaveKickOff(void);
void     LongBench_RestoreKickOff(void);

/* ---- the names (a substitute from place 17 on shows his name like anyone) ---- */
#define LB_NAME_SPRITE_BASE  LOOKS_SPRITES_END  /* (sprites past the game's table and the looks' sets: SDL) */
#define LB_NAME_SPRITES      (2 * LB_EXTRA_PLACES)
#define LB_ARROW_SPRITE      (LB_NAME_SPRITE_BASE + LB_NAME_SPRITES)   /* the arrow mirrored */
int32_t  LongBench_MirroredArrow(int32_t arrow);
/* The name tables' values for places 16.. (as _plOrdinalsTable / _plNamesLengthTableCopy). */
extern uint8_t g_lbOrdinals[2][LB_EXTRA_PLACES];
extern uint8_t g_lbNameLenCopy[2][LB_EXTRA_PLACES];
void     LongBench_MakeNameSprites(TeamGame *top, TeamGame *bottom);    /* MakeSpritesFromPlayerNames */
void     LongBench_InitNames(void);                                     /* CopyPlayerNameLengths */
/* SwapPlayerNameData for a place from 16 on: `team` 0 top, 1 bottom. */
void     LongBench_SwapNames(int32_t team, int16_t enterPlace, int16_t leavePlace);
/* SetCurrentPlayerName: the sprite and width of a name table value `ordinal` (0..15 the game's). */
int32_t  LongBench_NameSprite(int32_t team, uint8_t ordinal, int16_t *width);


/* ---- a replay (.SRP: the BNCH chunk, docs/REPLAY_FORMAT_V2.md) ---- */
#define LB_REPLAY_BYTES  (2 + 2 * LB_EXTRA_PLACES * 61)
uint32_t LongBench_ReplayWrite(uint8_t *out);           /* 0: no long bench, nothing to write */
void     LongBench_ReplayRead(const uint8_t *in, uint32_t len);  /* (len 0: none) */

/* SWOS_TEST_LONGBENCH=1 (bench_subs.c): the first stoppage calls the top team's bench, then the
 * menu's controls are a script's (the cursor down, a substitute on), with screenshots. */
int32_t  LongBench_TestCallBench(void);
void     LongBench_TestInput(uint16_t *dir, uint8_t *fire);

/* --long-bench-selftest: the table's lookups */
int32_t  LongBench_SelfTest(void);

#endif
