/*
 * world_supercup.h -- a world's Super Cups (src/world_supercup.c; docs/WORLD_2026_27.md 6h), as the
 * SWOS 96/97 Mod 4.0.5 / 4.1 plays them (tools/gplay.c sc_* / usc_*, tools/supercup.py,
 * tools/supercups2627.json; MIT, Davide Lorigliola).
 *
 * A national Super Cup -- one match on neutral ground (Italy, England, Germany, France, Brazil,
 * Mexico's Campeon de Campeones) or a final four (Spain, Turkey, Saudi Arabia: two semi-finals and a
 * final) -- between last season's league champion, cup winner and the others its rules name; and the
 * UEFA Super Cup, last season's Champions League winner v the Europa League's (the Conference
 * League's when one club holds both). At its week (the Mod's weeks, the career calendar's) the career
 * club's tie is played as a contest of one tie in slot 4 -- the Mod's gplay slot 4, here the slot the
 * season-end play-offs and the Coppa Italia Serie D take later, so it gives way once decided -- with
 * its rule (penalties straight after 90 minutes, or extra time first). Only the career club's: a Super
 * Cup it is not in is neither played nor simulated (the Mod's), nor is a summer one (from_season 2) in
 * the world's first season, whose entrants the game does not have; the December-to-February ones of
 * the first season are played by their real 2026-27 entrants. A final four's other semi-final is
 * decided when the career club's tie is built (the better placed of last season wins 3 in 5, the
 * Mod's generator seeded by the season and the national cup), and its final, the same way, when the
 * career club lost its semi-final -- so the SEASON WINNERS page of the career's league names this
 * season's winner. Won: a line of the season record.
 *
 * The entrants come from the season end: each country's top-division final order and its national
 * cup's winner and finalist (SuperCup_TableEnded / SuperCup_CupEnded), the three European holders
 * (SuperCup_HoldersEnded), and for Mexico the stage titles of last season (g_leagueWinners). All kept
 * with the career (save_format_json.c "world_supercup"); a save without them has none until its next
 * season end.
 */
#ifndef WORLD_SUPERCUP_H
#define WORLD_SUPERCUP_H

#include "swos_types.h"
#include "game_types.h"

enum {
    SC_CHAMPION = 1, SC_SECOND, SC_CUP_WINNER, SC_CUP_FINALIST, SC_THIRD, SC_FOURTH,
    SC_TITLE0, SC_TITLE1, SC_UEFA_CL, SC_UEFA_EL, SC_UEFA_ECL       /* (gplay.c SCR_*) */
};
#define WORLD_SUPERCUP_UEFA 0xFF        /* (a Super Cup's country: the UEFA Super Cup) */
#define WORLD_SUPERCUPS_MAX 16
#define WORLD_SUPERCUP_TABLE 24         /* a top division's final order kept */

/* A Super Cup (world_data.c, generated by world_import.py supercups from the converter's
 * supercups.json: the Mod's GP_SCT entry). */
typedef struct {
    uint8_t     country;        /* its league's country (include/world.h), or WORLD_SUPERCUP_UEFA */
    uint8_t     seed;           /* the Mod's contest id of the national cup (its generator's seed) */
    uint8_t     fromSeason;     /* 1, or 2: not in the world's first season */
    uint8_t     early;          /* the career club's tie built at the season start (shown from then on) */
    uint8_t     week;           /* the first match's (a final four: the semi-finals') */
    uint8_t     finalWeek;
    uint8_t     level;          /* 0 penalties after 90 minutes, 1 extra time then penalties */
    uint8_t     n;              /* 2 one match, 4 a final four (semi-finals 0 v 1, 2 v 3) */
    uint8_t     rule[4];        /* SC_* | the fallback's << 4 (its club already in: a double) */
    TeamId      first[4];       /* the world's first season's entrants (the real 2026-27 edition) */
    uint8_t     title[2];       /* SC_TITLE0 / 1's play-offs (the pack's ko_playoffs indices) */
    char       *name[2];        /* long, short */
    const char *record;         /* the season record's line */
} WorldSuperCup;

const WorldSuperCup *World_SuperCups(int32_t *count);   /* (the world's baked file, by src/world_baked.c; 0: none) */

/* What a season end leaves for the next season's Super Cups, per entry of World_SuperCups. */
typedef struct {
    uint8_t  season;            /* the season end it is of (world_cups.h's seasons + 1; 0: none) */
    uint8_t  n;                 /* the top division's clubs kept */
    uint16_t table[WORLD_SUPERCUP_TABLE];   /* its final order (team numbers {country, ordinal}) */
    uint8_t  cupSeason;         /* (the same, for the cup's) */
    uint16_t cup[2];            /* the national cup's winner, finalist (0xFFFF: none) */
} WorldSuperCupKept;

typedef struct {
    WorldSuperCupKept kept[WORLD_SUPERCUPS_MAX];
    uint8_t  holdSeason;        /* the season end the European holders are of (0: none) */
    uint16_t hold[3];           /* the Champions, Europa, Conference League's (0xFFFF: none) */
    /* this season's national Super Cup (gplay.c SC_ST's header) */
    uint8_t  season;            /* the season handled (seasons + 1; 0: none) */
    uint8_t  entry;             /* its World_SuperCups index */
    uint8_t  round;             /* 1 the career club's semi-final built, 2 won: its final due, 3 done */
    uint8_t  won;               /* the career club won it (the season record) */
    uint16_t other;             /* the other semi-final's winner */
    uint16_t winner;            /* this season's winner (0: not known) */
    /* this season's UEFA Super Cup (SC_U) */
    uint8_t  uSeason;           /* the season handled */
    uint8_t  uState;            /* 1 the career club's tie built, 3 done or not in it */
    uint8_t  uWon;
    uint16_t uWinner;
    /* the career club's tie in slot 4 */
    uint8_t  built;             /* 1 national, 2 the UEFA Super Cup's; 0 none (or decided) */
    uint8_t  final;             /* it is a final */
    uint8_t  week;
    uint16_t teamA, teamB;      /* home (listed first), away */
} WorldSuperCupState;

extern WorldSuperCupState g_worldSuperCup;

/* A new career (and a save without the state). */
void SuperCup_Reset(void);

/* The season end (career_season.c): a country's top division's final order (its table, after
 * LeaguePlayoffs_KeepTable); its national cup decided (the cup's winner and finalist); the
 * European cups' holders, before the qualifiers clear them. */
void SuperCup_TableEnded(uint8_t country);
void SuperCup_CupEnded(uint8_t country, uint16_t winner, uint16_t finalist);
void SuperCup_HoldersEnded(uint16_t cl, uint16_t el, uint16_t ecl);

/* The season start (an early tie built) and the calendar's advance (career_teams.c, beside
 * CupD_Step): the career club's tie into slot 4 when its week has come and the slot is free. */
void SuperCup_SeasonStart(void);
void SuperCup_Step(uint16_t week);

/* A tie decided (diy_competition.c): the career club's Super Cup tie's? */
void SuperCup_TieDecided(uint16_t team1, uint16_t team2, int32_t team2Won);

/* Slot 4: 2 the career club's Super Cup tie still to play, 1 decided (it gives way), 0 not ours. */
int32_t SuperCup_InSlot4(void);

/* A load: the tie under way back into slot 4. */
void SuperCup_RestoreSlot(void);

/* The round's name (_cupRoundStringTable index), -1: not ours. */
int32_t SuperCup_RoundStringIndex(uint8_t compId);

/* The season record's lines: the national Super Cup / the UEFA Super Cup won this season, 0: none. */
const char *SuperCup_RecordLine(int32_t uefa);

/* The SEASON WINNERS page of the career's league: this season's national Super Cup line --
 * its name, and its winner (0: to be played); 0 when there is none. */
const char *SuperCup_WinnersLine(uint16_t *winner);

#endif
