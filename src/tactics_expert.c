static TeamTactics  s_set[kExpert];         /* the set in play: k_expert with the start-up copy */
static TeamTactics *s_own[kExpert];         /* the game's own table entries while it is */
static int32_t      s_on;                   /* the setting */
static int32_t      s_applied;              /* _teamTacticsTable points at s_set */
static int32_t      s_suspended;            /* a match that plays the game's own */
static int32_t      s_held;                 /* the game's own code at work on its own (Hold) */
/* The players' order by formation (InitializeTacticsPositions, from the table) is the set's while
 * it is in play: the game's own kept here, and given back exactly, so that taking the set off
 * leaves every byte the match reads as it would have been without it. */
static TacticsPosition s_ownPos[kExpert], s_userPos[6];
static uint16_t        s_defensiveness[11];

static void apply(void)
{
    if (s_applied || !s_on || s_suspended || s_held)
        return;
    for (int32_t i = 0; i < kExpert; i++) {
        s_own[i] = (TeamTactics *)_teamTacticsTable[i];
        _teamTacticsTable[i] = &s_set[i];
        memcpy(&s_ownPos[i], _playersPositionsByTactics[i], sizeof s_ownPos[i]);
    }
    for (int32_t i = 0; i < 6; i++)
        memcpy(&s_userPos[i], _playersPositionsByTactics[kExpert + i], sizeof s_userPos[i]);
    memcpy(s_defensiveness, _tacticsPositionDefensiveness, sizeof s_defensiveness);
    InitializeTacticsPositions();               /* (the set's twelve; USER A-F as they were) */
    for (int32_t i = 0; i < 6; i++)
        memcpy(_playersPositionsByTactics[kExpert + i], &s_userPos[i], sizeof s_userPos[i]);
    memcpy(_tacticsPositionDefensiveness, s_defensiveness, sizeof s_defensiveness);
    s_applied = 1;
}

static void restore(void)
{
    if (!s_applied)
        return;
    for (int32_t i = 0; i < kExpert; i++) {
        _teamTacticsTable[i] = s_own[i];
        memcpy(_playersPositionsByTactics[i], &s_ownPos[i], sizeof s_ownPos[i]);
    }
    s_applied = 0;
}

void TacticsExpert_Set(int32_t expert)
{
    static int32_t ready;
    if (!ready) {
        for (int32_t i = 0; i < kExpert; i++)
            memcpy(&s_set[i], k_expert[i], sizeof s_set[i]);
        /* InitUserTactics' copy (menus.c): the 5-3-2's last two players' positions into the
         * 4-4-2 and SWEEP (slots 3, 0 and 8) -- made on SWOS 2020's copy of this set too. */
        memcpy(&s_set[0].positions[8], &s_set[3].positions[8], 2 * sizeof(PlayerPositions));
        memcpy(&s_set[8].positions[8], &s_set[3].positions[8], 2 * sizeof(PlayerPositions));
        ready = 1;
    }
    s_on = expert != 0;
    if (s_on)
        apply();
    else
        restore();
    fprintf(stderr, "[tactics] the built-in formations: %s\n",
            s_on ? "SWOS 2020's improved (expert) set, off line" : "the game's own");
}

int32_t TacticsExpert_On(void) { return s_on; }

/* The game's own code that writes through the table -- InitUserTactics (the 5-3-2 rows, the USER
 * A-F copies of the 4-4-2) and TacticsData_SelectRelease (a style's four) -- works on the game's
 * own formations, as it always has: the set comes off around it and goes back after. */
void TacticsExpert_Hold(void)
{
    s_held++;
    restore();
}

void TacticsExpert_Release(void)
{
    if (s_held && --s_held == 0)
        apply();
}

/* Kick-off (game_loop.c StartMatchSequence): online or in a rig, the game's own for this match. */
void TacticsExpert_MatchBegin(void)
{
    if (!s_applied)
        return;
    if (NetplayMatch_Enabled() || ReplayTest_Running() || SrpResim_Armed() || Rollback_Enabled() ||
        CareerAutopilot_Active()) {
        restore();
        s_suspended = 1;
        fprintf(stderr, "[tactics] this match plays the game's own formations (online or a test rig)\n");
    }
}

void TacticsExpert_MatchEnd(void)
{
    if (!s_suspended)
        return;
    s_suspended = 0;
    apply();
}

/* SWOS_CPU_TACTICS_TEST=1: the set goes on and off the table, around the game's own code and a
 * match online, and the table is the game's own after. PASS / FAIL on stdout. */
int32_t TacticsExpert_SelfTest(void)
{
    TeamTactics *before[kExpert];
    int32_t fails = 0;
    for (int32_t i = 0; i < kExpert; i++)
        before[i] = (TeamTactics *)_teamTacticsTable[i];
    TacticsExpert_Set(1);
    for (int32_t i = 0; i < kExpert; i++)
        fails += _teamTacticsTable[i] != &s_set[i];
    fails += memcmp(s_set[0].name, "4132", 5) != 0;          /* (SWOS 2020's names come with it) */
    fails += memcmp(&s_set[0].positions[8], &s_set[3].positions[8], 70) != 0;
    TacticsExpert_Hold();                                       /* (InitUserTactics) */
    for (int32_t i = 0; i < kExpert; i++)
        fails += _teamTacticsTable[i] != before[i];
    TacticsExpert_Release();
    fails += _teamTacticsTable[5] != &s_set[5];
    s_suspended = 1;                                            /* (as an online match's kick-off) */
    restore();
    fails += _teamTacticsTable[0] != before[0];
    TacticsExpert_MatchEnd();
    fails += _teamTacticsTable[0] != &s_set[0];
    TacticsExpert_Set(0);
    for (int32_t i = 0; i < kExpert; i++)
        fails += _teamTacticsTable[i] != before[i];
    printf("[cpu-tactics-test] %s (%d failures)\n", fails ? "FAIL" : "PASS", (int)fails);
    return fails ? 1 : 0;
}

