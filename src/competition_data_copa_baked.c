/* Per-career working *Copy — reconstructed from the template by InitCareer /
 * the save reconstruct (walking _careerContests), exactly like the heap *Copy on
 * SDL. BSS, zero-initialised. */
CompetitionTournament _copaLibertadoresCopy;

/* CopaBaked_Install — the Amiga analog of DataJson_InstallCompetitionGraph's
 * dynamic-Copa path: append the {template, copy} pair to _careerContests (so the
 * copy is built + saved) and register the template by compId (so Comp_ById(162)
 * resolves it). Called once at startup from FrontEndPreLoopSetup (frontend.c). */
void CopaBaked_Install(void)
{
    extern int  Comp_AppendCareerContest(Competition *, Competition *, uint16_t);
    extern void Comp_Register(Competition *);
    Comp_AppendCareerContest((Competition *)&_copaLibertadores,
                             (Competition *)&_copaLibertadoresCopy,
                             (uint16_t)sizeof _copaLibertadores);
    Comp_Register((Competition *)&_copaLibertadores);
}

