/*
 * sd_manifest.c -- which files the setup takes from the player's game, and where
 * each one lands. Names only: the files themselves come from the player's copy.
 *
 * Generated once from the trees the game used to ship (bin/data, bin/grafs,
 * bin/sound, bin/grafs_dos, bin/sound_dos), checked against the Amiga disks and
 * the GOG install; edit by hand from now on.
 */
#include "sd_manifest.h"

#include <string.h>

int32_t SdManifest_DosVideo(const char *dest)
{
    return !strncmp(dest, "video_dos/", 10) || !strncmp(dest, "sound_dos/flc/", 14) ||
           !strncmp(dest, "sound_dos/chairman/", 19);
}

int32_t SdManifest_DosOptional(const char *dest)
{
    return !strncmp(dest, "sound_dos/fx/", 13) || !strncmp(dest, "sound_dos/hard/", 15) ||
           !strncmp(dest, "sound_dos/pierce/", 17) || SdManifest_DosVideo(dest);
}

