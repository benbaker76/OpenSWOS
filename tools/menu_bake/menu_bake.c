/*
 * menu_bake.c -- the Amiga's menus of the mods, baked from their JSON at build time
 * (include/menu_baked.h; Makefile.amiga). A host program: src/menu_load_json.c built with
 * MENU_BAKE, the same builder the SDL game runs, so a baked menu is the menu the PC shows.
 *
 *   menu_bake OUT.c NAME=FILE.json ...
 *
 * NAME is what the game asks MenuJson_Load for ("practice/practiceMenu"). Writes OUT.c only
 * when it changes, so an unchanged menu does not relink the Amiga program.
 */
#include "menu_baked.h"
#include "menu_load_json.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* (menu_load_json.c's references the bake never calls) */
void SetExitMenuFlag(void) {}
char _aExit[] = "EXIT";
const char *tr(const char *key) { (void)key; return NULL; }
void *swos_io_realloc(void *p, uint32_t n) { return realloc(p, n); }

static char *slurp(const char *path, int *len)
{
    FILE *f = fopen(path, "rb");
    if (!f)
        return NULL;
    fseek(f, 0, SEEK_END);
    const long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    char *buf = (char *)malloc((size_t)n + 1);
    if (!buf || fread(buf, 1, (size_t)n, f) != (size_t)n) {
        free(buf);
        fclose(f);
        return NULL;
    }
    fclose(f);
    buf[n] = 0;
    *len = (int)n;
    return buf;
}

typedef struct { char *p; size_t n, cap; } Out;

static void put(Out *o, const char *fmt, ...) __attribute__((format(printf, 2, 3)));
#include <stdarg.h>
static void put(Out *o, const char *fmt, ...)
{
    va_list ap;
    for (;;) {
        va_start(ap, fmt);
        const int k = vsnprintf(o->p + o->n, o->cap - o->n, fmt, ap);
        va_end(ap);
        if (k >= 0 && o->n + (size_t)k < o->cap) {
            o->n += (size_t)k;
            return;
        }
        o->cap = o->cap * 2 + 4096;
        o->p = (char *)realloc(o->p, o->cap);
    }
}

static void put_cstring(Out *o, const char *s)
{
    put(o, "\"");
    for (; *s; s++) {
        const unsigned char c = (unsigned char)*s;
        if (c == '"' || c == '\\')
            put(o, "\\%c", c);
        else if (c < 32 || c > 126)
            put(o, "\\%03o", c);
        else
            put(o, "%c", c);
    }
    put(o, "\"");
}

int main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr, "usage: menu_bake OUT.c NAME=FILE.json ...\n");
        return 2;
    }
    Out o = { NULL, 0, 0 };
    o.cap = 65536;
    o.p = (char *)malloc(o.cap);
    put(&o, "/* Generated by tools/menu_bake (Makefile.amiga) from the mods' menu JSON. Do not edit. */\n"
            "#include \"menu_baked.h\"\n\n");
    int count = 0;
    for (int a = 2; a < argc; a++) {
        char *eq = strchr(argv[a], '=');
        if (!eq) {
            fprintf(stderr, "menu_bake: %s is not NAME=FILE\n", argv[a]);
            return 2;
        }
        *eq = 0;
        const char *name = argv[a], *path = eq + 1;
        int jl = 0;
        char *json = slurp(path, &jl);
        if (!json) {
            fprintf(stderr, "menu_bake: cannot read %s\n", path);
            return 1;
        }
        static uint8_t packed[65536];
        const int len = MenuJson_BuildPacked(json, jl, packed, (int)sizeof packed);
        const MenuBakedReloc *rel = NULL;
        const int nrel = MenuJson_BakeRelocs(&rel);
        if (len < 0 || nrel < 0) {
            fprintf(stderr, "menu_bake: %s (%s) did not build\n", name, path);
            return 1;
        }
        put(&o, "/* %s: %s */\nstatic const uint8_t m%d[%d] = {", name, path, count, len);
        for (int i = 0; i < len; i++)
            put(&o, "%s%u,", i % 24 ? "" : "\n    ", packed[i]);
        put(&o, "\n};\nstatic const MenuBakedReloc r%d[%d] = {\n", count, nrel ? nrel : 1);
        for (int i = 0; i < nrel; i++) {
            put(&o, "    { %u, %u, ", (unsigned)rel[i].offset, (unsigned)rel[i].kind);
            put_cstring(&o, rel[i].text);
            put(&o, " },\n");
        }
        if (!nrel)
            put(&o, "    { 0, 0, 0 },\n");
        put(&o, "};\n\n");
        free(json);
        argv[a] = (char *)name;     /* (for the table below) */
        count++;
    }
    put(&o, "const MenuBaked g_bakedMenus[] = {\n");
    for (int i = 0; i < count; i++) {
        put(&o, "    { ");
        put_cstring(&o, argv[2 + i]);
        put(&o, ", m%d, sizeof m%d, r%d, sizeof r%d / sizeof r%d[0] - (r%d[0].kind == 0) },\n", i, i, i, i, i, i);
    }
    if (!count)
        put(&o, "    { 0, 0, 0, 0, 0 },\n");
    put(&o, "};\nconst int32_t g_bakedMenuCount = %d;\n", count);

    {   /* only when it changed */
        int ol = 0;
        char *old = slurp(argv[1], &ol);
        if (old && (size_t)ol == o.n && memcmp(old, o.p, o.n) == 0) {
            free(old);
            return 0;
        }
        free(old);
    }
    FILE *f = fopen(argv[1], "wb");
    if (!f || fwrite(o.p, 1, o.n, f) != o.n) {
        fprintf(stderr, "menu_bake: cannot write %s\n", argv[1]);
        return 1;
    }
    fclose(f);
    fprintf(stderr, "menu_bake: %d menus -> %s\n", count, argv[1]);
    return 0;
}
