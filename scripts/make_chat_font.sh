#!/usr/bin/env bash
# make_chat_font.sh -- the chat's typeface, subset and embedded: src/chat_font_data.c
# (third_party/fonts/roboto_condensed/OPENSWOS.md). Needs Python's fonttools.
#
#   scripts/make_chat_font.sh
#
# The ranges must match kRanges in src/chat_font.c: what the chat accepts is what the font has.
set -euo pipefail
cd "$(dirname "$0")/.."

SRC=third_party/fonts/roboto_condensed/RobotoCondensed-Regular.ttf
OUT=src/chat_font_data.c
UNICODES="U+0020-007E,U+00A0-017F,U+2013-2014,U+2018-201E,U+2022,U+2026,U+20AC"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

python3 -m fontTools.subset "$SRC" --unicodes="$UNICODES" --layout-features=kern \
    --no-hinting --output-file="$tmp/chat.ttf"

python3 - "$tmp/chat.ttf" "$OUT" "$UNICODES" <<'EOF'
import sys
data = open(sys.argv[1], 'rb').read()
with open(sys.argv[2], 'w', newline='\n') as f:
    f.write('/* GENERATED by scripts/make_chat_font.sh -- do not edit.\n'
            ' * Roboto Condensed Regular 2.137, Copyright 2011 Google Inc., Apache License 2.0\n'
            ' * (third_party/fonts/roboto_condensed), subset to %s. */\n' % sys.argv[3])
    f.write('#ifdef SWOS_SDL_BUILD\n#include <stdint.h>\n\n')
    f.write('const uint32_t g_chatFontSize = %d;\n' % len(data))
    f.write('const uint8_t g_chatFont[%d] = {\n' % len(data))
    for i in range(0, len(data), 16):
        f.write('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n#endif\n')
print('%s: %d bytes' % (sys.argv[2], len(data)))
EOF
