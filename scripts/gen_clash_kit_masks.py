#!/usr/bin/env python3
"""gen_clash_kit_masks.py -- src/clash_kit_masks.inc from SWOS 2020's GK/REF CLASH KITS data.

SWOS 2020 (src/video/gkShadowPixels.h, refShadowPixels.h, by its authors) lists, per frame of
the goalkeeper's 58 and the referee's 11 sprites, the pixels that are NEVER recoloured: the
background and the drop shadow, whose colour is the keeper's jersey colour (8) or close to it.
Those frames are the same drawings in the Amiga's sprites (833.., 949.., 1159..) and the DOS
ones, so the lists apply to ours as they are. This writes them as one 16-bit row mask per
line (bit x = pixel x protected), 22 lines a frame: src/clash_kits.c reads them.

    python3 scripts/gen_clash_kit_masks.py [--swos2020 DIR]
"""
import argparse
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "src", "clash_kit_masks.inc")
CELL_W, CELL_H = 16, 22


def masks(path, frames):
    rows = [[0] * CELL_H for _ in range(frames)]
    for f, x, y in re.findall(r"\{(\d+),(\d+),(\d+)\}", open(path).read()):
        f, x, y = int(f), int(x), int(y)
        if f < frames and x < CELL_W and y < CELL_H:
            rows[f][y] |= 1 << x
    return rows


def emit(name, rows):
    out = ["static const uint16_t %s[%d][%d] = {" % (name, len(rows), CELL_H)]
    for r in rows:
        out.append("    { " + ", ".join("0x%04X" % v for v in r) + " },")
    out.append("};")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--swos2020", default=os.environ.get("SWOS2020_DIR", "/mnt/c/Projects/GitHub/swos-2020"))
    a = ap.parse_args()
    video = os.path.join(a.swos2020, "src", "video")
    gk = masks(os.path.join(video, "gkShadowPixels.h"), 58)
    ref = masks(os.path.join(video, "refShadowPixels.h"), 11)
    with open(OUT, "w", newline="\n") as f:
        f.write("/* Generated by scripts/gen_clash_kit_masks.py from SWOS 2020's gkShadowPixels.h and\n"
                " * refShadowPixels.h -- do not edit. Per frame, per line: bit x set = pixel x is the\n"
                " * background or the drop shadow, never recoloured (src/clash_kits.c). */\n")
        f.write(emit("kGkProtected", gk) + "\n")
        f.write(emit("kRefProtected", ref) + "\n")
    print("wrote", os.path.relpath(OUT, REPO))


if __name__ == "__main__":
    main()
