#!/usr/bin/env python3
"""gen_clash_kit_masks.py -- src/clash_kit_masks.inc from SWOS 2020's GK/REF CLASH KITS data.

SWOS 2020 (src/video/gkShadowPixels.h, refShadowPixels.h, by its authors) lists, per frame of
the goalkeeper's 58 and the referee's 11 sprites, the pixels that are NEVER recoloured: the
background and the drop shadow, whose colour is the keeper's jersey colour (8) or close to it.
Those frames are the same drawings in the Amiga's sprites (833.., 949.., 1159..) and the DOS
ones, so the lists apply to ours as they are. This writes them as one 16-bit row mask per
line (bit x = pixel x protected), 22 lines a frame: src/clash_kits.c reads them.

It also writes the referee of SWOS 2020's DLC "referee-clashkit" (sprite_referee/referee-clashkit/
referee-clashkit.bmp, by its authors): the original referee with his shirt in the keeper's jersey
colour (8), the shadow's, so it can be told from his black shorts, hair and shoes. The original's is
black all over; with CLASH KITS on, src/clash_kits.c draws this one in its place. 11 frames of
16x22, the colour indices as the game's sprites hold them (the BMP's background, 16, is 0).

    python3 scripts/gen_clash_kit_masks.py [--swos2020 DIR] [--referee BMP]
"""
import argparse
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "src", "clash_kit_masks.inc")
CELL_W, CELL_H = 16, 22


def masks(path, frames):
    rows = [[0] * CELL_H for _ in range(frames)]
    for f, x, y in re.findall(r"\{(\d+),(\d+),(\d+)\}", open(path).read()):
        f, x, y = int(f), int(x), int(y)
        if f < frames and x < CELL_W and y < CELL_H:
            rows[f][y] |= 1 << x
    return rows


def referee_bmp(path, frames):
    """An 8-bit BMP, `frames` cells of CELL_W x CELL_H side by side -> [frame][y][x] indices."""
    b = open(path, "rb").read()
    if b[:2] != b"BM":
        raise SystemExit("%s: not a BMP" % path)
    off = int.from_bytes(b[10:14], "little")
    w = int.from_bytes(b[18:22], "little", signed=True)
    h = int.from_bytes(b[22:26], "little", signed=True)
    bpp = int.from_bytes(b[28:30], "little")
    if bpp != 8 or w != frames * CELL_W or abs(h) != CELL_H:
        raise SystemExit("%s: want an 8-bit %dx%d BMP, got %d-bit %dx%d" % (path, frames * CELL_W, CELL_H, bpp, w, h))
    stride = (w + 3) & ~3
    cells = [[[0] * CELL_W for _ in range(CELL_H)] for _ in range(frames)]
    for y in range(CELL_H):
        row = b[off + (CELL_H - 1 - y if h > 0 else y) * stride:][:w]
        for x in range(w):
            v = row[x]
            cells[x // CELL_W][y][x % CELL_W] = 0 if v >= 16 else v
    return cells


def emit_pixels(name, cells):
    out = ["static const uint8_t %s[%d][%d][%d] = {" % (name, len(cells), CELL_H, CELL_W)]
    for c in cells:
        out.append("    {")
        for r in c:
            out.append("        { " + ", ".join("%2d" % v for v in r) + " },")
        out.append("    },")
    out.append("};")
    return "\n".join(out)


def emit(name, rows):
    out = ["static const uint16_t %s[%d][%d] = {" % (name, len(rows), CELL_H)]
    for r in rows:
        out.append("    { " + ", ".join("0x%04X" % v for v in r) + " },")
    out.append("};")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--swos2020", default=os.environ.get("SWOS2020_DIR", "/mnt/c/Projects/GitHub/swos-2020"))
    ap.add_argument("--referee", default=os.environ.get("SWOS2020_REFEREE_CLASHKIT",
                    os.path.join(REPO, "scripts", "clash_kits", "referee-clashkit.bmp")))
    a = ap.parse_args()
    video = os.path.join(a.swos2020, "src", "video")
    gk = masks(os.path.join(video, "gkShadowPixels.h"), 58)
    ref = masks(os.path.join(video, "refShadowPixels.h"), 11)
    kit = referee_bmp(a.referee, 11)
    with open(OUT, "w", newline="\n") as f:
        f.write("/* Generated by scripts/gen_clash_kit_masks.py from SWOS 2020's gkShadowPixels.h and\n"
                " * refShadowPixels.h -- do not edit. Per frame, per line: bit x set = pixel x is the\n"
                " * background or the drop shadow, never recoloured (src/clash_kits.c). */\n")
        f.write(emit("kGkProtected", gk) + "\n")
        f.write(emit("kRefProtected", ref) + "\n")
        f.write("/* SWOS 2020's DLC referee-clashkit: the referee with his shirt in colour 8 (see above). */\n")
        f.write(emit_pixels("kRefClashKit", kit) + "\n")
    print("wrote", os.path.relpath(OUT, REPO))


if __name__ == "__main__":
    main()
