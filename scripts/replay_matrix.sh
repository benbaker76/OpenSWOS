### What the shape of that list says

Twenty-six of the forty-seven are a **DOS-vs-Amiga difference** — mostly timing
constants, one a whole data set (30), and five (28, 29, 31, 40, 47) artefacts of the
static recompilation itself rather than anything anyone chose. That is what a rig replaying DOS
recordings against an Amiga port is built to find, and none of them changes what
this port does on the Amiga. The other twenty-one are porting defects that would be
just as wrong on either machine, and they cluster into a handful of shapes worth
knowing by name:

- **Inverted conditions** (7, 21, 23) — an `ble`/`bge` whose branch target is
  the *reject* label reads naturally as the accept condition.
- **Off-by-one bounds** (19, 24, 25) — `bcs`/`bhi`/`blt` are not `<=`.
- **A flag that is really a value** (12, 15) — a routine whose contract is a
  condition code can still leave a number in the register at the `rts`.
- **An access wider than the field** (33) — `tst.l` on a `dc.w` reaches the
  next one; the endian-helper rule, arriving as a read.
- **A register that is really a parameter** (32) — nothing assigns it inside the
  routine because the caller already did; a `movem.l a1-a3,-(sp)` around the
  `bsr` is the tell.
- **Believing the annotation** (34) — the comments in `data/SWOS2.s` come from
  the DOS IDA database; they are evidence of intent and none about the
  instructions beside them. `swos.asm` is a second witness for one grep.
- **Reading the listing too literally** (10, 18, 20, 22) — an equate applied to
  a foreign pointer, a table read off its own front, a copy to the wrong symbol,
  and an arm the mask above it had already made unreachable.
- **A shared tail split in two** (37, 43) — the port gave a branch its own arm
  where the listing had already answered by jumping into somebody else's. The
  mirror image of 22 and 29: not code that never runs, but code reached from
  somewhere the port did not look. 43 is the same shape seen from the other
  side: two blocks that read as duplicates because they compute the same value
  and test the same threshold, and differ only in the arm the listing writes
  as a bare fall-through.
- **A fall-through that became a return** (38) — a chain of `cmpi/bne` has a
  default arm whether or not anyone wrote one, and it is wherever the last
  `bne` points. Factored into a `void` helper it silently becomes "return",
  and the C reads exactly like what it was meant to be.

### Where the corpus stands

**No stop in this corpus is a defect in this port.** What is left is one
recording's tail and a handful of single frames, and every one of them is
something the `.RGD` does not record:

| stop | frames lost | what |
|---|---:|---|
| `zkz-10174427` 26448, `zkz-10173518` 25490 | 272 | `currentGameTick` drifting in real time across a fade |
| five recordings' last frame | 5 | an input edge inside the frame |

Both classes are written up in docs/TESTS.md ("The tick is a real-time
counter", and the terminal-frame entry under "Known non-comparable state").
Neither can be closed against a DOS recording; both would be closed by a
recording made from THIS build, which is what section 8's Amiga dumper is for.

### ! The bench frame is ESTIMATED, not recovered

The one place the rig guesses, and it is worth reading before trusting any
result that turns on a substitution.

The recording under-determines the bench call by exactly one frame. One key
reaches the game down two independent latches: the recording carries the
POLLED BITMASK (`p1_controls` bit 6 -> `pl1SecondaryFire` ->
`TeamGeneralInfo.secondaryFire`, written at GameLoop line 703) while the bench
opens off the BUFFERED SCANCODE (`bench1Called`, set only in `MainKeysCheck`
at line 666). A scancode can arrive a frame after the bitmask sees the key
held, and nothing in the record times that queue.

The corpus has three presses and neither placement is right for all of them —
`zkz-11215003` f117 same-frame, `zkz-11215003` f11479 and `playa-10090613`
f11222 one frame later. The rig defers unless `gameStatePl` is 0, which is
right on all three and is **fitted to those three, not derived**. Every
deferral says ESTIMATED in the log, and `src/replay_test.c` carries the whole
argument. A bench-frame match is evidence of nothing.

What would make it a recovered fact is a recording that carries `bench1Called`
itself — which the Amiga dumper (docs/TESTS.md section 8) would, being our own
build. It was worth 11% of this corpus, which is the strongest argument for
building it, quite apart from the `onScreen` ceiling below.

### The open lead

`zkz-10174427` at 26448 of 26624 is the last stop that is not a terminal
frame, and it is the real-time tick again rather than a defect. `MarkPlayer`
blinks the player-mark on `currentGameTick & 0x10`, and the recording's
`sprite[28].image_index` reads that bit back once a frame. Its windows sit on
the 32-frame grid for most of the match and then move off it by two at f26450
— the reference's tick has gained two counts somewhere the frame count did
not. See "The tick is a real-time counter".

One earlier reading of that field needs care, and it is a good trap to know:
the blink also INVERTS partway through the match, which looks exactly like a
16-count drift and is not. `MarkPlayer` picks the team by the tick bit and
then shows the mark only if THAT team has a marked player, so when the marked
player moves from one side to the other the pattern flips with the tick
untouched.

That is the honest reading of "as accurate as this corpus can measure". It is
NOT "the port is correct" — see the `onScreen` ceiling in docs/TESTS.md, which
is why the Amiga dumper is a requirement rather than a nice-to-have.

Five retractions are documented too. Three were data that never executes: a
"rewritten" DOS forward line, a hybrid tactics table, and a DOS-specific 4-4-2.
The fourth was about the corpus itself — this document long said the recordings
were SWOS++ rather than the retail DOS game, and treated five sprite fields as
permanently unmatchable because of it. swos-port is a **static recompilation**:
the recordings are the original game's own code executing. The five fields are
its C++ `Sprite::init()` memsetting SWOS's static sprite table away before
frame 0, and on every one of them this port holds the value `data/SWOS2.s`
gives.

The fifth is this document's own worst call, and it is the same mistake once
more. Four recordings that stopped on fire flags and team alternation were
filed as "swos-port's C++ control layer, and no change to this port will move
them". The recordings are made by SWOS++ instrumenting the DOS binary; they
were never swos-port's C++ at all. Defect 37 is what three of the four
actually were, and it moved `playa-10144556` from 1696 to complete,
`zkz-10190651` from 2570 to complete and `zkz-10173518` from 5051 to 25586 —
a third of the whole corpus, sitting behind a paragraph that said not to look.
**A class of "cannot be fixed" is a claim, and it needs the same evidence as a
fix.**
