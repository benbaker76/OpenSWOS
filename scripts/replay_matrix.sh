#!/usr/bin/env bash
# Replay every recording in tests/dos at every comparison level and print the
# results as the Markdown that docs/TESTS_RESULTS.md is made of.
#
#   scripts/replay_matrix.sh                  # human-readable progress + table
#   scripts/replay_matrix.sh > docs/TESTS_RESULTS.md
#   scripts/replay_matrix.sh --levels info    # one level only (much faster)
#   scripts/replay_matrix.sh --tsv            # raw rows, for diffing two runs
#
# Everything goes to stdout; progress goes to stderr, so redirecting stdout to
# the doc still shows you where it is. Takes a few minutes: each cell replays
# until it diverges, and the long recordings run tens of thousands of frames.
set -uo pipefail
export SWOS_WORLD="${SWOS_WORLD:-9697}"   # (its corpus / careers are 96/97's, whatever SWOS.ini says)
cd "$(dirname "$0")/.."

LEVELS="scalars teams info sprites"
FORMAT=md
SKIP_V12=1          # the one v1.2 file has no resolved (header, frame) pair

while [ $# -gt 0 ]; do
    case "$1" in
        --levels) LEVELS=$2; shift 2 ;;
        --tsv)    FORMAT=tsv; shift ;;
        --all-files) SKIP_V12=0; shift ;;
        -h|--help) sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "unknown argument: $1" >&2; exit 1 ;;
    esac
done

[ -x bin/SWOS ] || { echo "bin/SWOS not built — run make" >&2; exit 1; }
ls tests/dos/*.RGD.gz >/dev/null 2>&1 || {
    echo "no recordings in tests/dos — see docs/TESTS.md section 1" >&2; exit 1; }

TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
ROWS=$TMP/rows.tsv
: > "$ROWS"

for f in tests/dos/*.RGD.gz; do
    n=$(basename "$f" .RGD.gz)
    [ "$SKIP_V12" = 1 ] && [ "$n" = zkz-11122841 ] && continue
    for lvl in $LEVELS; do
        echo "  $n / $lvl" >&2
        log=$TMP/$n-$lvl.log
        timeout 1800 scripts/replay_test.sh --level "$lvl" "$f" > "$log" 2>&1
        rc=$?
        ver=$(grep -oE 'v1\.[0-9]' "$log" | head -1)
        tot=$(grep -oE '[0-9]+ frames \(' "$log" | grep -oE '^[0-9]+' | head -1)
        got=$(grep -oE 'diverged after [0-9]+' "$log" | grep -oE '[0-9]+$' | head -1)
        # A clean PASS says "PASS — N/N frames matched"; take THAT line, not the
        # first "... 500/4064 frames matched" progress tick, which is what the
        # old `head -1` picked up and reported as a regression to frame 500.
        [ -z "$got" ] && got=$(grep -oE 'PASS — [0-9]+/[0-9]+ frames matched' "$log" |
                               grep -oE '[0-9]+/' | head -1 | tr -d /)
        [ -z "$got" ] && got=$(grep -oE '[0-9]+/[0-9]+ frames matched' "$log" | tail -1 | cut -d/ -f1)
        fld=$(grep -A1 'DIVERGENCE at frame' "$log" | tail -1 |
              sed -E 's/^\[replay\] +//; s/ +recorded=.*//')
        [ "$rc" = 0 ] && fld='(complete)'
        # Setup-state check: the recording's own per-player match values
        # (docs/TESTS.md "The recording grades our formation data").
        val=$(grep -oE 'player values: [0-9]+/[0-9]+' "$log" | head -1 | sed 's/player values: //')
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
            "$n" "${ver:-?}" "${tot:-?}" "$lvl" "${got:-?}" "${fld:-?}" "${val:-?}" >> "$ROWS"
    done
done

if [ "$FORMAT" = tsv ]; then cat "$ROWS"; exit 0; fi

COMMIT=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
DIRTY=$(git status --porcelain -- src include scripts Makefile 2>/dev/null | head -1)
[ -n "$DIRTY" ] && COMMIT="$COMMIT + uncommitted changes"

cat <<EOF
# Replay results

Where each recorded match stops matching this build, per comparison level.
Generated by \`scripts/replay_matrix.sh\`; regenerate it after any change that
could touch the simulation. See docs/TESTS.md for the rig, the levels and what
the non-comparable classes mean.

- **Build:** \`$COMMIT\`, $(date +%Y-%m-%d)
- **Selftest:** $(cd bin && ./SWOS --replay-selftest 2>&1 | grep -oE '[0-9]+/[0-9]+ reference vectors match' || echo '(not run)')
- **Corpus:** $(ls tests/dos/*.RGD.gz | wc -l) recordings in \`tests/dos\`$([ "$SKIP_V12" = 1 ] && echo ', the unresolved v1.2 file skipped')
- **Corpus coverage:** $(awk -F'\t' '
      { tot[$1]=$3; got[$4]+=$5; }
      END {
          for (n in tot) all += tot[n];
          split("scalars teams info sprites", L, " ");
          out = "";
          for (i = 1; i <= 4; i++)
              out = out sprintf("%s%s %.1f%%", (i>1 ? ", " : ""), L[i], 100*got[L[i]]/all);
          printf "%s of %d recorded frames", out, all;
      }' "$ROWS")

A cell is the frame the replay reached before the first mismatching field, and
the percentage beside it is that frame as a share of the recording's own length
(the "frames" column). 100% means the replay ran the whole recording without a
single bound field ever disagreeing.

"values" is the setup-state check that runs before frame 0: the recording's own
per-player match values (\`PlayerFile.cachedMatchValue\`, 16 per team) against
what this build's \`GetPlayerPrice\` computes. It is reported, not fatal — see
docs/TESTS.md.

| recording | ver | frames | values | scalars | teams | info | sprites |
|---|---|---:|:---:|---:|---:|---:|---:|
EOF

cut -f1 "$ROWS" | awk '!seen[$0]++' | while read -r n; do
    ver=$(awk -F'\t' -v n="$n" '$1==n{print $2; exit}' "$ROWS")
    tot=$(awk -F'\t' -v n="$n" '$1==n{print $3; exit}' "$ROWS")
    val=$(awk -F'\t' -v n="$n" '$1==n{print $7; exit}' "$ROWS")
    line="| \`$n\` | $ver | $tot | ${val:--}"
    for lvl in scalars teams info sprites; do
        v=$(awk -F'\t' -v n="$n" -v l="$lvl" '$1==n && $4==l{print $5; exit}' "$ROWS")
        if [ -n "$v" ] && [ "$v" != '?' ] && [ -n "$tot" ] && [ "$tot" != '?' ]; then
            pct=$(awk -v a="$v" -v b="$tot" 'BEGIN{printf "%.1f", 100*a/b}')
            line="$line | $v (${pct}%)"
        else
            line="$line | ${v:--}"
        fi
    done
    echo "$line |"
done

cat <<'EOF'

## First mismatching field

The field named is the *first* one to disagree, not necessarily the cause — a
cheap level reports a symptom the next level down would have caught earlier.

| recording | level | frame | field |
|---|---|---:|---|
EOF
awk -F'\t' '{printf "| `%s` | %s | %s | `%s` |\n", $1, $4, $5, $6}' "$ROWS"
