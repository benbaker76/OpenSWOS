"""Stage a private test runtime; prepared game data is never added to git."""
import argparse
from pathlib import Path
import subprocess
import zipfile

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--assets", required=True, type=Path, help="Prepared SWOS assets folder")
args = parser.parse_args()
# The Makefile generates this ignored header too; Android does not run make's
# parse-time shell command. Keep its commit/date/dirty meaning on Windows.
commit = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=root).decode().strip()
date = subprocess.check_output(["git", "log", "-1", "--format=%cd", "--date=short"], cwd=root).decode().strip()
if subprocess.run(["git", "diff", "--quiet", "HEAD", "--", "src", "include", "Makefile", "Makefile.amiga", "scripts", "android"], cwd=root).returncode:
    commit += "-dirty"
header = root / "include" / "swos_build.h"
stamp = ("/* GENERATED by scripts/stage_android.py; do not commit. */\n"
         "#ifndef SWOS_BUILD_H\n#define SWOS_BUILD_H\n"
         f'#define SWOS_BUILD_ID "{commit}"\n'
         f'#define SWOS_BUILD_ID_UC "{commit.upper()}"\n'
         f'#define SWOS_BUILD_DATE "{date}"\n#endif\n')
if not header.exists() or header.read_text() != stamp:
    header.write_text(stamp)
assets = args.assets.resolve()
if not (assets / "data" / "TEAM.000").is_file():
    parser.error(f"No prepared team data at {assets}")
trees = {"data", "data_json", "grafs", "grafs_aga", "grafs_dos", "grafs_2020", "grafs_jag", "sound", "sound_dos"}
files = {}
for tree in trees:
    for path in (assets / tree).rglob("*"):
        if path.is_file():
            files[path.relative_to(assets).as_posix()] = path
# Current project menus/translations and credits override prepared copies.
tracked = subprocess.check_output(["git", "ls-files", "-z", "bin"], cwd=root).decode().split("\0")
for name in tracked:
    path = Path(name)
    if len(path.parts) > 2 and path.parts[1] in trees and (root / path).is_file():
        files[path.relative_to("bin").as_posix()] = root / path
out = root / "build" / "android-assets" / "runtime.zip"
out.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as archive:
    for name, path in sorted(files.items()):
        archive.write(path, name)
print(f"Staged {len(files)} files ({out.stat().st_size / 1048576:.1f} MiB): {out}")
