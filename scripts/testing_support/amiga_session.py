#!/usr/bin/env python3
"""FS-UAE debug-session bring-up for THIS machine's layout (native Windows
FS-UAE + win32 m68k gdb, daemon under Cygwin) — the docs/AMIGA_DEBUGGING.md
procedure automated:

  1. fresh FS-UAE with remote_debugger + trigger SYS:SWOS2 (the port is
     ONE-SHOT per emulator session — never probe it, never attach twice)
  2. gdb_proxy daemon in amiga mode, gdb started with NO file
     (AMIGASCOPE_ELF_NOARG): connect FIRST, symbols after
  3. qOffsets -> add-symbol-file at the RELOCATED hunk bases
     (plain symbol-file loads link addresses: plausible but wrong)
  4. verify a write sticks (the stock stub silently ignores writes — only
     the benbaker76 fork's FS-UAE has the M/P/G packets)
  5. skip the loader intro (break ShowLoaderIntroSequence; return; continue)
  6. land stopped at MenuInputInjectPoint — the flow framework's anchor.

Run from Cygwin:  python3 scripts/testing_support/amiga_session.py <action>

  up       boot (or reuse a stopped session); cleans up after an owned
           emulator/gdb that has exited, never touches a running one
  status   the truth about the owned session: none / dead / stale build /
           stopped at <symbol> / running (handed over)
  pause    take a running session back: interrupt, then run on to the menu
           anchor if a menu is up, else stay paused where it stopped
  release  hand the game over: breakpoints off, resume in the background
           (gdb stays usable, so `pause` can take it back)
  down     stop the owned processes only
"""
import os
import re
import subprocess
import sys
import time
import json
import shutil
import hashlib
from pathlib import Path

REPO_CYG = "/cygdrive/c/Users/A7126/orca/OpenSWOS"
REPO_WIN = "C:/Users/A7126/orca/OpenSWOS"
TOOLS = "/cygdrive/c/Users/A7126/tools/vscode-amiga-debug/bin/win32"
FSUAE = f"{TOOLS}/fs-uae/fs-uae.exe"
GDB = f"{TOOLS}/opt/bin/m68k-amiga-elf-gdb.exe"
KICKSTART_WIN = "C:/Users/A7126/Downloads/kickstarts/amiga-os-310-a1200.rom"
ELF_CYG = f"{REPO_CYG}/bin/SWOS2.elf"
ELF_WIN = f"{REPO_WIN}/bin/SWOS2.elf"
PROXY = f"{REPO_CYG}/scripts/testing_support/amiga_proxy.py"
SESSION = Path(f"{REPO_CYG}/build/amiga-ui")
SESSION.mkdir(parents=True, exist_ok=True)
OWNER = SESSION / "owner.json"
os.environ["SWOS_GDB_SOCKET"] = "/tmp/swos-amiga-ui.sock"
sys.path.insert(0, f"{REPO_CYG}/scripts")
from testing_support.fastproxy import FastGdb
FAST = FastGdb(proxy=PROXY)
CFG = "/cygdrive/c/Users/A7126/AppData/Local/Temp/swos-a1200-debug.fs-uae"
NATIVE_LOG = "/cygdrive/c/Users/A7126/FS-UAE/Cache/Logs/fs-uae.log.txt"
PORT = 2345

CONFIG = f"""# generated by testing_support/amiga_session.py
amiga_model = A1200
kickstart_file = {KICKSTART_WIN}
hard_drive_0 = {REPO_WIN}/build/amiga-ui/drawer
chip_memory = 2048
fast_memory = 8192
fullscreen = 0
warp_mode = {os.environ.get('SWOS_AMIGA_WARP', '0')}
uae_cpu_speed = {os.environ.get('SWOS_AMIGA_CPU_SPEED', 'real')}
window_width = 960
window_height = 600
remote_debugger = 120
remote_debugger_port = {PORT}
remote_debugger_trigger = SYS:SWOS2
"""


def sh(*args, timeout=30):
    return subprocess.run(list(args), capture_output=True, text=True,
                          timeout=timeout)


def proxy(*args, timeout=30):
    if args[0] == "cmd":
        return FAST.cmd(args[1], timeout=float(args[3]) if len(args) > 3 else timeout)
    return FAST._simple(*args)


def cmd(c, timeout=20):
    return proxy("cmd", c, "--timeout", str(timeout), timeout=timeout + 15)


def build_identity():
    return {name: hashlib.sha256((Path(REPO_CYG) / "bin" / name).read_bytes()).hexdigest()
            for name in ("SWOS2", "SWOS2.elf")}


def process_identity(pid):
    """Cygwin PID, Windows PID and start ticks; never trust a reused PID."""
    root = Path(f"/proc/{int(pid)}")
    try:
        fields = (root / "stat").read_text().rsplit(")", 1)[1].split()
        return {"pid": pid, "winpid": int((root / "winpid").read_text()),
                "start": fields[19], "command": (root / "cmdline").read_text()}
    except (FileNotFoundError, ProcessLookupError):
        return None


def child_identity(parent_pid, name):
    """The Cygwin child of `parent_pid` whose command line contains `name`."""
    for entry in Path("/proc").iterdir():
        if not entry.name.isdigit():
            continue
        try:
            if (int((entry / "ppid").read_text()) == int(parent_pid)
                    and name in (entry / "cmdline").read_text()):
                return process_identity(int(entry.name))
        except (FileNotFoundError, ProcessLookupError, ValueError):
            continue
    return None


ROLES = ("emulator", "daemon", "gdb")


def dead_roles(owner):
    """Recorded processes that are gone. gdb matters as much as the emulator:
    the debugger port is one-shot, so a session whose gdb died is undrivable."""
    return [role for role in ROLES
            if role in owner and process_identity(owner[role]["pid"]) != owner[role]]


def down():
    if not OWNER.exists():
        return True
    owner = json.loads(OWNER.read_text())
    if not all(role in owner for role in ("emulator", "daemon")):
        raise RuntimeError("Legacy owner record lacks process identities; refusing unsafe teardown.")
    for role in ("gdb", "daemon", "emulator"):
        if role not in owner:
            continue
        recorded = owner[role]
        if process_identity(recorded["pid"]) == recorded:
            result = sh("taskkill", "/PID", str(recorded["winpid"]), "/T", "/F")
            for _ in range(20):
                if process_identity(recorded["pid"]) != recorded:
                    break
                time.sleep(0.1)
            if result.returncode and process_identity(recorded["pid"]) == recorded:
                raise RuntimeError(f"Failed to stop owned {role}: {result.stdout} {result.stderr}")
    OWNER.unlink()
    Path("/tmp/swos-amiga-ui.sock").unlink(missing_ok=True)
    return True


T0 = time.time()


def log(msg):
    print(f"[amiga +{time.time() - T0:6.1f}s] {msg}", flush=True)


def up():
    global T0
    T0 = time.time()
    if OWNER.exists():
        owner = json.loads(OWNER.read_text())
        gone = dead_roles(owner)
        if gone:
            # Nothing of this session can be driven or seen any more (an emulator
            # closed by hand, or a gdb that died); stopping what is left of it is
            # identity-checked, so other sessions stay untouched.
            log(f"owned session is dead ({', '.join(gone)} exited); cleaning it up")
            down()
        else:
            if owner.get("build") != build_identity():
                raise RuntimeError("Build changed or unverified. Run down then up to boot the new executable.")
            h = proxy("health").strip()
            if h.startswith("OK stopped"):
                log("REUSED existing test session: " + h)
                return 0
            if "running" in h:
                raise RuntimeError("The owned session is running (handed over, maybe being played). "
                                   "`pause` takes it back if that is fine; `up` will not.")
            raise RuntimeError(f"Recorded session is not stopped/healthy ({h}); refusing to restart any emulator.")
    if "fs-uae.exe" in sh("tasklist", "/FI", "IMAGENAME eq fs-uae.exe").stdout:
        raise RuntimeError("An existing FS-UAE session is running; leaving it untouched.")
    if Path("/tmp/swos-amiga-ui.sock").exists():
        raise RuntimeError("Private debugger socket already exists; refusing to replace it.")
    drawer = SESSION / "drawer"
    drawer.mkdir(exist_ok=True)
    for name in ("c", "s", "data", "grafs", "grafs_aga", "sound", "save"):
        shutil.copytree(Path(REPO_CYG) / "bin" / name, drawer / name, dirs_exist_ok=True)
    # The classic competitions, converted on the PC (docs/CLASSIC_COMPETITIONS.md): not in
    # the repository, so only when a developer has made them.
    if (Path(REPO_CYG) / "bin" / "classic").is_dir():
        shutil.copytree(Path(REPO_CYG) / "bin" / "classic", drawer / "classic", dirs_exist_ok=True)
    shutil.copy2(Path(REPO_CYG) / "bin/SWOS2", drawer / "SWOS2")
    (drawer / "data/CHALGEN.DAT").unlink(missing_ok=True)
    if not os.path.exists(ELF_CYG):
        print("FATAL: bin/SWOS2.elf not built")
        return 1
    with open(CFG, "w", newline="\n") as f:
        f.write(CONFIG)
    cfg_win = "C:/Users/A7126/AppData/Local/Temp/swos-a1200-debug.fs-uae"
    log("launching FS-UAE (debug config, trigger SYS:SWOS2)")
    emu = subprocess.Popen([FSUAE, cfg_win],
                     cwd=os.path.dirname(FSUAE),
                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    owner = {"emulator": process_identity(emu.pid), "build": build_identity(),
             "cpu_speed": os.environ.get("SWOS_AMIGA_CPU_SPEED", "real"),
             "warp": os.environ.get("SWOS_AMIGA_WARP", "0"),
             "created": time.time()}
    OWNER.write_text(json.dumps(owner))

    log("starting gdb_proxy daemon (gdb attaches; blocks until the Amiga "
        "boots to the SYS:SWOS2 trigger)")
    env = dict(os.environ,
               AMIGASCOPE_GDB=GDB,
               AMIGASCOPE_ELF=ELF_CYG,
               AMIGASCOPE_ELF_NOARG="1")
    daemon_log = open("/tmp/amiga_daemon.log", "w")
    daemon = subprocess.Popen(["python3", PROXY, "daemon", "--mode", "amiga",
                      "--host", "127.0.0.1", "--port", str(PORT)],
                     env=env, stdout=daemon_log, stderr=daemon_log,
                     start_new_session=True)
    owner["daemon"] = process_identity(daemon.pid)
    OWNER.write_text(json.dumps(owner))

    # the daemon creates the socket immediately; health goes OK when the
    # SYS:SWOS2 trigger fires (tens of seconds into a cold boot)
    deadline = time.time() + 180
    while time.time() < deadline:
        h = proxy("health").strip()
        if h.startswith("OK"):
            break
        time.sleep(2)
    else:
        print("FATAL: attach never became healthy; daemon log:")
        print(open("/tmp/amiga_daemon.log").read()[-2000:])
        return 1
    log("attached (Amiga booted to the trigger): " + proxy("health").strip())
    # gdb is the daemon's child; with it recorded, `status` sees it die too.
    gdb = child_identity(daemon.pid, "m68k-amiga-elf-gdb")
    if gdb:
        owner["gdb"] = gdb
        OWNER.write_text(json.dumps(owner))
    else:
        log("warning: gdb process not found under the daemon; status cannot see it die")

    # ---- relocated symbols (docs/AMIGA_DEBUGGING.md) ----
    r = cmd("maintenance packet qOffsets", timeout=20)
    m = re.search(r'received:\s*"([0-9a-fA-F;]+)"', r)
    if not m:
        print("FATAL: qOffsets gave no reply:", r[-400:])
        return 1
    text, data, chip, bss = (int(x, 16) for x in m.group(1).split(";"))
    log(f"qOffsets: text={text:#x} data={data:#x} chip={chip:#x} bss={bss:#x}")
    cmd("set confirm off")
    cmd("set pagination off")
    r = cmd(f"add-symbol-file {ELF_WIN} {text:#x} -s .data {data:#x} "
            f"-s BSSInChip.MEMF_CHIP {chip:#x} -s .bss {bss:#x}",
            timeout=180)
    log("symbols loaded (8.6 MB DWARF add-symbol-file)")

    # ---- write capability check (fork's stub only) ----
    cmd("set var _fire = 1")
    chk = cmd("print _fire")
    cmd("set var _fire = 0")
    if "= 1" not in chk:
        print("FATAL: memory write did not stick — this FS-UAE is the stock "
              "stub (no M/P/G packets); writes silently no-op. See "
              "scripts/amiga/amigascope/README.md.")
        return 1
    log("write check: OK (fork stub)")

    # ---- skip the loader intro, land at the menu anchor ----
    log("skipping the loader intro; running to the menu anchor "
        "(the game loads its data files here)")
    cmd("break ShowLoaderIntroSequence")
    cmd("commands\nsilent\nreturn\ncontinue\nend")
    cmd("break MenuInputInjectPoint")
    cmd("continue", timeout=5)
    proxy("waitstop", "180", timeout=200)

    # ---- SELF-CHECK: "UP" is a verified claim, never a hope ----
    # 1. the emulator process actually exists
    tl = sh("tasklist", "/FI", "IMAGENAME eq fs-uae.exe").stdout
    if "fs-uae.exe" not in tl:
        print("FAILED self-check: fs-uae.exe is not running")
        return 1
    # 2. the target is cleanly stopped
    h = proxy("health").strip()
    if not h.startswith("OK stopped"):
        print(f"FAILED self-check: target not cleanly stopped ({h})")
        return 1
    # 3. ...exactly at the menu anchor, with symbols resolving
    pc = cmd("info symbol $pc", timeout=15)
    if "MenuInputInjectPoint" not in pc:
        print("FAILED self-check: stopped PC is not MenuInputInjectPoint:")
        print("  " + " / ".join(pc.strip().splitlines()[:2]))
        return 1
    log(f"UP (verified): fs-uae alive, {h}, PC=MenuInputInjectPoint")
    owner["cold_seconds"] = round(time.time() - T0, 3)
    OWNER.write_text(json.dumps(owner, indent=2))
    return 0


def status():
    """One line, first word machine-readable: NONE DEAD STALE STOPPED RUNNING
    UNHEALTHY. Never changes the session."""
    if not OWNER.exists():
        return "NONE no owned session"
    owner = json.loads(OWNER.read_text())
    gone = dead_roles(owner)
    if gone:
        return f"DEAD {', '.join(gone)} exited (`up` cleans up and boots)"
    stale = owner.get("build") != build_identity()
    h = proxy("health").strip()
    if h.startswith("OK stopped"):
        where = cmd("info symbol $pc", timeout=10).split(" in section")[0].strip()
        verdict = f"STOPPED at {where}"
    elif "running" in h:
        verdict = "RUNNING (handed over; `pause` takes it back)"
    else:
        verdict = f"UNHEALTHY {h}"
    if stale:
        verdict = "STALE " + verdict + " -- bin/SWOS2 changed since boot"
    return verdict


def pause(menu_wait=3.0):
    """Take a running session back. Stops wherever the game is, then gives it
    `menu_wait` seconds to reach the menu anchor (a menu runs it every frame;
    a match never does). Returns where it ended up, stopped either way."""
    h = proxy("health").strip()
    if h.startswith("OK stopped"):
        return "already stopped"
    if "running" not in h:
        raise RuntimeError(f"Session is neither stopped nor running: {h}")
    r = cmd("interrupt", timeout=5)
    r += proxy("waitstop", "10", timeout=25)
    if "WAITSTOP timeout" in r:
        raise RuntimeError("interrupt did not stop the target: " + r[-400:])
    cmd("enable breakpoints")          # the anchor (release disabled them)
    cmd("continue &", timeout=5)
    r = proxy("waitstop", str(menu_wait), timeout=menu_wait + 15)
    if "WAITSTOP timeout" in r:
        cmd("interrupt", timeout=5)
        proxy("waitstop", "10", timeout=25)
    where = cmd("info symbol $pc", timeout=10).split(" in section")[0].strip()
    return f"paused at {where}" + ("" if "MenuInputInjectPoint" in where
                                   else " (no menu reached: in a match?)")


def release():
    """Hand the game over running, debugger kept: no breakpoint stops it, and
    a background resume leaves gdb able to `interrupt` later."""
    h = proxy("health").strip()
    if "running" in h:
        return "already running"
    cmd("disable breakpoints")
    r = cmd("continue &", timeout=5)
    if "Continuing." not in r:
        raise RuntimeError("background resume failed: " + r[-400:])
    return "released (running; `pause` takes it back)"


if __name__ == "__main__":
    action = sys.argv[1] if len(sys.argv) > 1 else "up"
    if action == "down":
        down()
        print("[amiga] down")
        sys.exit(0)
    if action == "status":
        print(status())
        sys.exit(0)
    if action in ("pause", "release"):
        print(f"[amiga] {pause() if action == 'pause' else release()}")
        sys.exit(0)
    sys.exit(up())
