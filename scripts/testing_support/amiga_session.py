#!/usr/bin/env python3
"""FS-UAE debug-session bring-up for THIS machine's layout (native Windows
FS-UAE + win32 m68k gdb, daemon under Cygwin) — the docs/AMIGA_DEBUGGING.md
procedure automated:

  1. fresh FS-UAE with remote_debugger + trigger SYS:SWOS2 (the port is
     ONE-SHOT per emulator session — never probe it, never attach twice)
  2. gdb_proxy daemon in amiga mode, gdb started with NO file
     (AMIGASCOPE_ELF_NOARG): connect FIRST, symbols after
  3. qOffsets -> add-symbol-file at the RELOCATED hunk bases
     (plain symbol-file loads link addresses: plausible but wrong)
  4. verify a write sticks (the stock stub silently ignores writes — only
     the benbaker76 fork's FS-UAE has the M/P/G packets)
  5. skip the loader intro (break ShowLoaderIntroSequence; return; continue)
  6. land stopped at MenuInputInjectPoint — the flow framework's anchor.

Run from Cygwin:  python3 scripts/testing_support/amiga_session.py up
"""
import os
import re
import subprocess
import sys
import time

REPO_CYG = "/cygdrive/c/Users/A7126/orca/OpenSWOS"
REPO_WIN = "C:/Users/A7126/orca/OpenSWOS"
TOOLS = "/cygdrive/c/Users/A7126/tools/vscode-amiga-debug/bin/win32"
FSUAE = f"{TOOLS}/fs-uae/fs-uae.exe"
GDB = f"{TOOLS}/opt/bin/m68k-amiga-elf-gdb.exe"
KICKSTART_WIN = "C:/Users/A7126/Downloads/kickstarts/amiga-os-310-a1200.rom"
ELF_CYG = f"{REPO_CYG}/bin/SWOS2.elf"
ELF_WIN = f"{REPO_WIN}/bin/SWOS2.elf"
PROXY = f"{REPO_CYG}/scripts/amiga/amigascope/gdb_proxy.py"
CFG = "/cygdrive/c/Users/A7126/AppData/Local/Temp/swos-a1200-debug.fs-uae"
NATIVE_LOG = "/cygdrive/c/Users/A7126/FS-UAE/Cache/Logs/fs-uae.log.txt"
PORT = 2345

CONFIG = f"""# generated by testing_support/amiga_session.py
amiga_model = A1200
kickstart_file = {KICKSTART_WIN}
hard_drive_0 = {REPO_WIN}/bin
chip_memory = 2048
fast_memory = 8192
fullscreen = 0
window_width = 960
window_height = 600
remote_debugger = 120
remote_debugger_port = {PORT}
remote_debugger_trigger = SYS:SWOS2
"""


def sh(*args, timeout=30):
    return subprocess.run(list(args), capture_output=True, text=True,
                          timeout=timeout)


def proxy(*args, timeout=30):
    r = sh("python3", PROXY, *args, timeout=timeout + 10)
    return r.stdout + r.stderr


def cmd(c, timeout=20):
    return proxy("cmd", c, "--timeout", str(timeout), timeout=timeout + 15)


def down():
    sh("taskkill", "/F", "/IM", "fs-uae.exe", timeout=20)
    # the native gdb detaches from the Cygwin process table once its parent
    # python exits, so pkill alone leaves stale m68k gdb processes behind
    sh("taskkill", "/F", "/IM", "m68k-amiga-elf-gdb.exe", timeout=20)
    subprocess.run(["bash", "-lc",
                    "pkill -9 -f 'gdb_proxy.py daemon' 2>/dev/null; "
                    "pkill -9 -f 'm68k-amiga-elf-gdb' 2>/dev/null; "
                    "rm -f /tmp/swos_gdb.sock"], timeout=20)
    for p in (NATIVE_LOG,):
        try:
            os.remove(p)
        except OSError:
            pass
    # VERIFY the kills landed before anyone launches a new emulator — a
    # lingering fs-uae/gdb pair fights the fresh session over port 2345.
    deadline = time.time() + 15
    while time.time() < deadline:
        tl = sh("tasklist").stdout
        if "fs-uae.exe" not in tl and "m68k-amiga-elf-gdb" not in tl:
            return True
        time.sleep(0.5)
    print("WARNING: old fs-uae/gdb still alive 15s after taskkill",
          flush=True)
    return False


T0 = time.time()


def log(msg):
    print(f"[amiga +{time.time() - T0:6.1f}s] {msg}", flush=True)


def up():
    global T0
    T0 = time.time()
    log("tearing down any previous session")
    if down():
        log("teardown verified: no fs-uae.exe, no m68k gdb left")
    else:
        log("teardown NOT clean — aborting rather than racing the old session")
        return 1
    if not os.path.exists(ELF_CYG):
        print("FATAL: bin/SWOS2.elf not built")
        return 1
    with open(CFG, "w", newline="\n") as f:
        f.write(CONFIG)
    cfg_win = "C:/Users/A7126/AppData/Local/Temp/swos-a1200-debug.fs-uae"
    log("launching FS-UAE (debug config, trigger SYS:SWOS2)")
    subprocess.Popen([FSUAE, cfg_win],
                     cwd=os.path.dirname(FSUAE),
                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    log("starting gdb_proxy daemon (gdb attaches; blocks until the Amiga "
        "boots to the SYS:SWOS2 trigger)")
    env = dict(os.environ,
               AMIGASCOPE_GDB=GDB,
               AMIGASCOPE_ELF=ELF_CYG,
               AMIGASCOPE_ELF_NOARG="1")
    daemon_log = open("/tmp/amiga_daemon.log", "w")
    subprocess.Popen(["python3", PROXY, "daemon", "--mode", "amiga",
                      "--host", "127.0.0.1", "--port", str(PORT)],
                     env=env, stdout=daemon_log, stderr=daemon_log,
                     start_new_session=True)

    # the daemon creates the socket immediately; health goes OK when the
    # SYS:SWOS2 trigger fires (tens of seconds into a cold boot)
    deadline = time.time() + 180
    while time.time() < deadline:
        h = proxy("health").strip()
        if h.startswith("OK"):
            break
        time.sleep(2)
    else:
        print("FATAL: attach never became healthy; daemon log:")
        print(open("/tmp/amiga_daemon.log").read()[-2000:])
        return 1
    log("attached (Amiga booted to the trigger): " + proxy("health").strip())

    # ---- relocated symbols (docs/AMIGA_DEBUGGING.md) ----
    r = cmd("maintenance packet qOffsets", timeout=20)
    m = re.search(r'received:\s*"([0-9a-fA-F;]+)"', r)
    if not m:
        print("FATAL: qOffsets gave no reply:", r[-400:])
        return 1
    text, data, chip, bss = (int(x, 16) for x in m.group(1).split(";"))
    log(f"qOffsets: text={text:#x} data={data:#x} chip={chip:#x} bss={bss:#x}")
    cmd("set confirm off")
    cmd("set pagination off")
    r = cmd(f"add-symbol-file {ELF_WIN} {text:#x} -s .data {data:#x} "
            f"-s BSSInChip.MEMF_CHIP {chip:#x} -s .bss {bss:#x}",
            timeout=180)
    log("symbols loaded (8.6 MB DWARF add-symbol-file)")

    # ---- write capability check (fork's stub only) ----
    cmd("set var _fire = 1")
    chk = cmd("print _fire")
    cmd("set var _fire = 0")
    if "= 1" not in chk:
        print("FATAL: memory write did not stick — this FS-UAE is the stock "
              "stub (no M/P/G packets); writes silently no-op. See "
              "scripts/amiga/amigascope/README.md.")
        return 1
    log("write check: OK (fork stub)")

    # ---- skip the loader intro, land at the menu anchor ----
    log("skipping the loader intro; running to the menu anchor "
        "(the game loads its data files here)")
    cmd("break ShowLoaderIntroSequence")
    cmd("commands\nsilent\nreturn\ncontinue\nend")
    cmd("break MenuInputInjectPoint")
    cmd("continue", timeout=5)
    proxy("waitstop", "180", timeout=200)

    # ---- SELF-CHECK: "UP" is a verified claim, never a hope ----
    # 1. the emulator process actually exists
    tl = sh("tasklist", "/FI", "IMAGENAME eq fs-uae.exe").stdout
    if "fs-uae.exe" not in tl:
        print("FAILED self-check: fs-uae.exe is not running")
        return 1
    # 2. the target is cleanly stopped
    h = proxy("health").strip()
    if not h.startswith("OK stopped"):
        print(f"FAILED self-check: target not cleanly stopped ({h})")
        return 1
    # 3. ...exactly at the menu anchor, with symbols resolving
    pc = cmd("info symbol $pc", timeout=15)
    if "MenuInputInjectPoint" not in pc:
        print("FAILED self-check: stopped PC is not MenuInputInjectPoint:")
        print("  " + " / ".join(pc.strip().splitlines()[:2]))
        return 1
    log(f"UP (verified): fs-uae alive, {h}, PC=MenuInputInjectPoint")
    return 0


if __name__ == "__main__":
    action = sys.argv[1] if len(sys.argv) > 1 else "up"
    if action == "down":
        down()
        print("[amiga] down")
        sys.exit(0)
    sys.exit(up())
