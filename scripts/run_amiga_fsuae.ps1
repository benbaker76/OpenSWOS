# run_amiga_fsuae.ps1 -- run the Amiga (m68k) build under FS-UAE on Windows.
#
#   scripts\run_amiga_fsuae.ps1
#   scripts\run_amiga_fsuae.ps1 -Kickstart "D:\roms\kick31-a1200.rom"
#   scripts\run_amiga_fsuae.ps1 -Build          # make -f Makefile.amiga first
#
# bin/ is mounted as the BOOT volume, so its s/startup-sequence runs SYS:SWOS2 and
# then c/UAEquit -- quitting the game closes the emulator. That is the same layout
# the release drawer ships (CLAUDE.md, "the Amiga drop"), so what you test here is
# what a player gets.
#
# Requirements, and the traps behind each:
#  * A Kickstart 3.1 (A1200) ROM. Copyrighted, so nothing ships one -- point
#    -Kickstart at your own dump, or set $env:SWOS_KICKSTART.
#  * 2 MB chip + 8 MB fast. Use fast_memory, NOT zorro_iii_memory: the A1200 has
#    no Zorro bus, so zorro_iii_memory is silently ignored and the game dies with
#    "not enough memory available".
#  * The game data must actually be in bin/ (data grafs grafs_aga sound) and
#    bin/save must exist -- the Amiga build reads relative paths from the mounted
#    volume and will NOT create save/. The SDL build reads the per-user assets
#    folder instead, so a tree that runs fine under SDL can still be empty here.
#    -StageData copies them out of the assets folder without touching the
#    git-tracked project files.
param(
    [string]$Kickstart = $env:SWOS_KICKSTART,
    [string]$FsUae     = $env:SWOS_FSUAE,
    [switch]$Build,
    [switch]$StageData
)

$ErrorActionPreference = "Stop"
$RepoRoot = Split-Path -Parent $PSScriptRoot
$Bin      = Join-Path $RepoRoot "bin"

# --- locate FS-UAE (ships inside the amiga-debug fork's toolchain) ------------
if (-not $FsUae) {
    $cands = @(
        "$env:USERPROFILE\tools\vscode-amiga-debug\bin\win32\fs-uae\fs-uae.exe"
        "$env:USERPROFILE\.vscode\extensions\bartmanabyss.amiga-debug-*\bin\win32\fs-uae\fs-uae.exe"
    )
    foreach ($c in $cands) {
        $hit = Get-Item $c -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($hit) { $FsUae = $hit.FullName; break }
    }
}
if (-not $FsUae -or -not (Test-Path $FsUae)) {
    throw "fs-uae.exe not found. Pass -FsUae <path> or set `$env:SWOS_FSUAE."
}

# --- locate a Kickstart ------------------------------------------------------
if (-not $Kickstart) {
    $guess = Get-ChildItem "$env:USERPROFILE\Downloads\kickstarts" -Filter "*A1200*.rom" -ErrorAction SilentlyContinue |
             Sort-Object Name | Select-Object -Last 1
    if ($guess) { $Kickstart = $guess.FullName }
}
if (-not $Kickstart -or -not (Test-Path $Kickstart)) {
    throw "No A1200 Kickstart ROM. Pass -Kickstart <file.rom> or set `$env:SWOS_KICKSTART."
}

if ($Build) {
    # The native-Windows Amiga build needs the bundled gnumake + WINDOWS=1; a POSIX
    # shell mangles $(CURDIR) into /c/... and the compiler chokes. See docs/BUILDING.md.
    $ext = Split-Path (Split-Path $FsUae)       # ...\bin\win32
    $env:PATH = "$ext\opt\bin;$ext;" + $env:PATH
    & "$ext\gnumake.exe" -f (Join-Path $RepoRoot "Makefile.amiga") WINDOWS=1 -j4
    if ($LASTEXITCODE -ne 0) { throw "Amiga build failed" }
}

if ($StageData) {
    $assets = Join-Path $env:USERPROFILE "Documents\SWOS\assets"
    if (-not (Test-Path $assets)) { throw "assets folder not found: $assets (run OpenSWOS Setup)" }
    foreach ($d in @("data","grafs","grafs_aga","sound")) {
        # /XC /XN /XO => only copy files that are NOT already there, so the
        # git-tracked project files (LOADER76.RAW, 1UP.WAV, ...) always win.
        robocopy "$assets\$d" "$Bin\$d" /E /XC /XN /XO /NFL /NDL /NJH /NJS /NP | Out-Null
    }
    robocopy "$assets\amiga\grafs_aga" "$Bin\grafs_aga" /E /NFL /NDL /NJH /NJS /NP | Out-Null
}
New-Item -ItemType Directory -Force -Path (Join-Path $Bin "save") | Out-Null

if (-not (Test-Path (Join-Path $Bin "SWOS2"))) {
    throw "bin/SWOS2 not built. Run with -Build, or see docs/BUILDING.md."
}

$cfg = Join-Path ([System.IO.Path]::GetTempPath()) "swos-a1200.fs-uae"
@"
# generated by scripts/run_amiga_fsuae.ps1
amiga_model = A1200
kickstart_file = $Kickstart
hard_drive_0 = $Bin
chip_memory = 2048
fast_memory = 8192
fullscreen = 0
window_width = 1440
window_height = 900
"@ | Set-Content -Path $cfg -Encoding ASCII

Write-Host "FS-UAE  : $FsUae"
Write-Host "Kickstart: $Kickstart"
Write-Host "DH0      : $Bin  (startup-sequence -> SYS:SWOS2)"
Start-Process -FilePath $FsUae -ArgumentList $cfg -WorkingDirectory (Split-Path $FsUae)
