#!/usr/bin/env python3
"""Writes src/player_looks_art.c from the SWOS 96/97 Mod's tools/shavedart.json: Marco's hand-drawn
shaved heads (every frame of a player set, light and dark skin) and the two face icons, as data for
src/player_looks.c (docs/WORLD_2026_27.md §6l; the Mod's tools/shavedart.py says what the file holds).

    python3 -I scripts/gen_shaved_art.py --repo /mnt/d/Projects/GitHub/swos-9697-mod [--tag v4.1.2]
    python3 -I scripts/gen_shaved_art.py --json shavedart.json

A head is the cells to write over a raw player frame (raw colours: -1 keep; 13 the Mod's skull tone,
which our frames draw in the skin's own lightest shade -- the Mod's half / EGA mode). The frames'
table gives each of the 101 frames its head and the column of its head box, dark then light.
"""
import argparse
import json
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'player_looks_art.c')
NF = 101
MAXH, MAXW = 8, 12


def load(args):
    if args.json:
        return json.load(open(args.json))
    text = subprocess.run(['git', '-C', args.repo, 'show', f'{args.tag}:tools/shavedart.json'],
                          check=True, capture_output=True).stdout
    return json.loads(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--repo')
    ap.add_argument('--tag', default='v4.1.2')
    ap.add_argument('--json')
    args = ap.parse_args()
    if not args.json and not args.repo:
        ap.error('--repo or --json')
    art = load(args)
    assert len(art['frames']) == NF
    out = ['/*',
           ' * player_looks_art.c -- GENERATED by scripts/gen_shaved_art.py from the SWOS 96/97 Mod\'s',
           ' * tools/shavedart.json (%s): the shaved heads drawn by Marco, every frame of a player set in' % args.tag,
           ' * light and dark skin, and the two face icons. Used by src/player_looks.c. Do not edit.',
           ' */',
           '#include "player_looks.h"',
           '']
    for skin in ('light', 'dark'):
        heads = art['heads'][skin]
        out.append('const LooksArtHead g_looksArt%s[LOOKS_ART_HEADS] = {' % skin.capitalize())
        assert len(heads) == len(art['heads']['light'])
        for h in heads:
            rows = h['rows']
            assert len(rows) <= MAXH and max(len(r) for r in rows) <= MAXW
            cells = []
            for r in rows:
                cells.append('{' + ','.join(str(v) for v in r + [-1] * (MAXW - len(r))) + '}')
            out.append('    { %d, %d, %d, %d, { %s } },' % (h['ry'], h['rx'], len(rows), len(rows[0]), ', '.join(cells)))
        out.append('};')
        out.append('')
    out.append('const uint8_t g_looksArtFrames[LOOKS_ART_FRAMES][3] = {   /* head, dark box column, light box column */')
    for i in range(0, NF, 8):
        out.append('    ' + ' '.join('{%d,%d,%d},' % tuple(f) for f in art['frames'][i:i + 8]))
    out.append('};')
    out.append('')
    out.append('const uint8_t g_looksArtIcons[2][8][16] = {   /* light, dark: menu colours, 0 transparent */')
    for skin in ('light', 'dark'):
        rows = art['icons'][skin]
        assert len(rows) == 8 and all(len(r) == 16 for r in rows)
        out.append('    {')
        for r in rows:
            out.append('        {' + ','.join(str(v) for v in r) + '},')
        out.append('    },')
    out.append('};')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print(f'{os.path.relpath(OUT)}: {len(art["heads"]["light"])} heads a skin, {NF} frames, 2 icons')


if __name__ == '__main__':
    main()
